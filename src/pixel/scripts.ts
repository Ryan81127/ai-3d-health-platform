import type { Layer, Movie, Scene } from './engine';

type O = Record<string, unknown>;
type N = number | [number, number];
const bg = (c = 1, pat?: string, c2?: number): Layer => ['bg', { c, pat, c2 }];
const title = (text: string, sub = '8-BIT 像素科普'): Layer => ['title', { text, sub }];
const lab = (text: string, x: number, y: number, o: O = {}): Layer => ['label', { text, x, y, ...o }];
const org = (kind: string, x: number, y: number, s: N = 1, o: O = {}): Layer => ['organ', { kind, x, y, s, ...o }];
const pt = (kind: string, mode: string, x: number, y: number, w: N, h: N, n: N = 12, o: O = {}): Layer => ['parts', { kind, mode, x, y, w, h, n, ...o }];
const man = (state: string, x: N = 96, y = 74, o: O = {}): Layer => ['person', { state, x, y, ...o }];
const ic = (kind: string, x: number, y: number, at = 0, o: O = {}): Layer => ['icon', { kind, x, y, at, ...o }];
const arr = (x0: number, y0: number, x1: number, y1: number, c = 10, blink = false): Layer => ['arrow', { x0, y0, x1, y1, c, blink }];
const ves = (o: O): Layer => ['vessel', o];
const gauge = (val: number | [number, number], text: string, x = 172, y = 18): Layer => ['gauge', { val, text, x, y }];
const sc = (cap: string, layers: Layer[], d = 5): Scene => ({ cap, layers, d });
const row = (kinds: string[], y = 54, gap = 30): Layer[] => kinds.map((k, i) => ic(k, 96 + (i - (kinds.length - 1) / 2) * gap, y, i * .12, { box: 1 }));
const open = (t: string, cap: string): Scene => sc(cap, [bg(1, 'stars'), title(t)], 4);
const todo = (cap: string, kinds: string[]): Scene => sc(cap, [bg(1, 'grid', 0), lab('我能做什麼', 96, 10, { align: 'center', edge: 11 }), ...row(kinds, 58)], 6);
const doctor = (cap: string, extra: Layer[] = []): Scene => sc(cap, [bg(1, 'floor', 5), man('ok', 70, 74, { c: 13 }), ic('doctor', 126, 62, 0, { box: 7 }), ic('stethoscope', 150, 62, .2), ...extra]);
